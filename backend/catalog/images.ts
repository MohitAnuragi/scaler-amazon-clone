export function productImage(key: string, variant = 1): string {
  const photoId = PHOTOS[key] ?? PHOTOS.smartphone;
  if (photoId.startsWith("http")) return photoId;
  const crop = variant === 2 ? "&crop=entropy" : variant === 3 ? "&crop=faces" : "";
  return `https://images.unsplash.com/photo-${photoId}?w=600&h=600&fit=crop&bg=f8f8f8&auto=format&q=80${crop}`;
}

export function productImageSet(key: string, altText: string) {
  if (key === "book" || key === "bookAlt") {
    const cover = bookCoverImage(resolveBookTitle(altText) ?? altText);
    return [1, 2, 3, 4].map((n, i) => ({
      url: cover,
      altText: i === 0 ? altText : `${altText} — view ${n}`,
      sortOrder: i + 1,
      isPrimary: i === 0,
    }));
  }

  return [1, 2, 3, 4].map((n, i) => ({
    url: productImage(key, n),
    altText: i === 0 ? altText : `${altText} — view ${n}`,
    sortOrder: i + 1,
    isPrimary: i === 0,
  }));
}

export function bookCoverImage(title: string): string {
  return `https://covers.openlibrary.org/b/title/${encodeURIComponent(title)}-L.jpg?default=false`;
}

function resolveBookTitle(value: string) {
  for (const [pattern, title] of BOOK_TITLES) {
    if (pattern.test(value)) return title;
  }
  return null;
}
